const TEXT_TOOLS = new Set([
  "create_text_layer",
  "update_text_layer",
  "create_shapes_from_text",
  "export_text_to_file"
]);

const TEXT_LAYOUT_PROMPT_PATTERN = new RegExp(
  [
    // English keywords: typography, font, text, layout, participants, performers, speakers, titles, plaques, credits
    "\\b(?:text|texts|typography|typographic|font|fonts|fontsize|title|titles|caption|captions|plaque|plaques|credits?|typeset(?:ting)?|kerning|leading|tracking)\\b",
    "\\b(?:lower[- ]third(?:s)?|line[- ]break(?:s)?)\\b",
    "\\b(?:participant|participants|performer|performers|speaker|speakers|artist|artists)\\b",
    // Russian keywords: типографика, текст, шрифт, кегль, титры, плашка, надпись, заголовок, участники, исполнители, верстка
    "(?:типографик[а-яё]*|текст[а-яё]*|шрифт[а-яё]*|кегл[а-яё]*|титр[а-яё]*|плашк[а-яё]*|надпис[а-яё]*|афиш[а-яё]*)",
    "(?:^|[^а-яё])им[яеё][а-яё]*",
    "(?:заголов[а-яё]+|участник[а-яё]*|исполнител[а-яё]*|верстк[а-яё]*|вёрстк[а-яё]*)"
  ].join("|"),
  "i"
);

function isTextLayoutRequest(prompt, selectedTools = []) {
  if (Array.isArray(selectedTools)) {
    for (const tool of selectedTools) {
      const name = typeof tool === "string" ? tool : (tool && tool.name);
      if (name && TEXT_TOOLS.has(name)) {
        return true;
      }
    }
  }
  const text = String(prompt || "");
  return TEXT_LAYOUT_PROMPT_PATTERN.test(text);
}

module.exports = {
  TEXT_LAYOUT_POLICY,
  TEXT_TOOLS,
  TEXT_LAYOUT_PROMPT_PATTERN,
  isTextLayoutRequest
};
