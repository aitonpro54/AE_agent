"use strict";
const assert = require("assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const {createAutonomousSessionManager} = require("../mcp-server/autonomous-session");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "ae-persistent-autonomy-"));
const statePath = path.join(root, "state.json");
let now = 100000, panel = {panelConnectionId:"panel-a",panelGeneration:"1",seenAt:now};
const make = (extra = {}) => createAutonomousSessionManager({now:()=>now,panelState:()=>panel,statePath,...extra});
const identity = () => ({panelConnectionId:panel.panelConnectionId,panelGeneration:panel.panelGeneration});
try {
  let manager = make();
  assert.strictEqual(manager.publicStatus().desiredEnabled, false);
  assert.throws(()=>manager.activate({panelConnectionId:"stranger",panelGeneration:"1"}), /not the active/);
  manager.activate(identity());
  now += 3 * 60 * 60 * 1000; panel.seenAt = now;
  assert.strictEqual(manager.publicStatus().active, true, "AUT01 permanent enabled");
  const firstAuthority = manager.authorization();
  assert(!JSON.stringify(manager.publicStatus()).includes(firstAuthority.sessionHash), "grant never public");
  manager = make();
  assert.strictEqual(manager.publicStatus().desiredEnabled, true, "AUT03 restart keeps desired on");
  assert.strictEqual(manager.authorization(), null, "restart needs trusted reconnect");
  panel.panelGeneration = "2"; manager.observePanel(identity());
  assert.strictEqual(manager.authorization().authorized, true);
  assert.notStrictEqual(manager.authorization().sessionHash, firstAuthority.sessionHash, "restart cannot revive old grant");
  panel.panelGeneration = "3"; manager.observePanel(identity());
  assert.strictEqual(manager.publicStatus().active, true, "AUT02 panel reload trusted generation");
  assert.throws(()=>manager.observePanel({panelConnectionId:"stranger",panelGeneration:"4"}), /identity/);
  assert.throws(()=>manager.observePanel({panelConnectionId:"panel-a",panelGeneration:"2"}), /generation/);
  panel.seenAt = now - 16000;
  assert.strictEqual(manager.publicStatus().desiredEnabled, true);
  assert.strictEqual(manager.publicStatus().connectionReady, false, "AUT15 disconnected waiting");
  panel.seenAt = now;
  manager.revoke(identity());
  assert.strictEqual(make().publicStatus().desiredEnabled, false, "AUT04 off survives restart");
  fs.writeFileSync(statePath, "broken");
  assert.strictEqual(make().publicStatus().desiredEnabled, false, "AUT05 corrupt off");
  fs.writeFileSync(statePath, JSON.stringify({active:true,expiresAt:"2099-01-01",schema:1}));
  assert.strictEqual(make().publicStatus().desiredEnabled, false, "AUT06 old temporary off");
  manager = make(); manager.activate(identity());
  const failing = make({writeState:()=>{throw new Error("fixture IO failure");}});
  failing.observePanel(identity());
  const off = failing.revoke(identity());
  assert.strictEqual(off.desiredEnabled, false, "AUT14 revoke immediately even if write fails");
  assert(off.persistenceError);
  assert.strictEqual(failing.authorization(), null);
  assert.throws(()=>failing.activate(identity()), /persist/i);
  assert.strictEqual(failing.authorization(), null);
  const panelJs = fs.readFileSync(path.join(__dirname,"../cep-panel/panel.js"),"utf8");
  const panelHtml = fs.readFileSync(path.join(__dirname,"../cep-panel/index.html"),"utf8");
  assert(!/20 minutes|20 мин|remainingMs/.test(panelJs + panelHtml), "AUT13 no countdown");
  assert(panelJs.includes("desiredEnabled") && panelJs.includes("persistenceError"));
  console.log(JSON.stringify({ok:true,cases:["AUT01","AUT02","AUT03","AUT04","AUT05","AUT06","AUT10","AUT13","AUT14","AUT15"],live:false}));
} finally { fs.rmSync(root,{recursive:true,force:true}); }
